# ---------------------------------------------------------------------------
# Canonicalization. All spans index into canonical text, never raw text.
# ---------------------------------------------------------------------------

def canonicalize(raw: str) -> tuple[str, str]:
    """Normalize document text. Returns (canonical_text, sha256_hex).

    Deterministic and stable. Deliberately does NOT case-fold, strip
    punctuation, or normalize units -- case is signal for entity mentions and
    unit handling belongs in the validator where it can be typed.
    """
    t = unicodedata.normalize("NFC", raw)
    t = t.replace("\r\n", "\n").replace("\r", "\n")
    t = re.sub(r"[ \t\u00a0]+", " ", t)
    t = re.sub(r" *\n", "\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    t = t.strip()
    return t, hashlib.sha256(t.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Spans
# ---------------------------------------------------------------------------

class Span(BaseModel):
    start: int = Field(..., ge=0)   # inclusive, offset into canonical text
    end: int = Field(..., ge=0)     # exclusive
    text_sha: str

    @model_validator(mode="after")
    def _check(self):
        if self.end <= self.start:
            raise ValueError("zero-width or inverted span")
        return self

    def slice(self, canonical_text: str) -> str:
        return canonical_text[self.start:self.end]


# ---------------------------------------------------------------------------
# Study profile -- gates which fields apply
# ---------------------------------------------------------------------------

StudyFeature = Literal[
    # has_wet_lab gates fields that apply to any bench work regardless of assay
    # (centrifugation, reagent identity, assay protocols). Without it, purely
    # computational papers accumulate false gaps on every wet-lab field.
    "has_wet_lab",
    "has_animals",
    "has_cell_lines",
    "has_qpcr",
    "has_flow_cytometry",
    "has_western_blot",
    "has_ihc",
    "has_xenograft",
    "has_drug_treatment",
]


class StudyProfile(BaseModel):
    """Which experiment types this paper contains. Drives applicability."""
    features: dict[StudyFeature, bool]
    evidence: dict[StudyFeature, Span] = {}

    def has(self, feature: str) -> bool:
        return bool(self.features.get(feature, False))  # type: ignore[arg-type]



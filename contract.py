Verdict = Literal[
    "FIELD_OK",           # present and usable
    "FIELD_ABSENT",       # not stated anywhere
    "FIELD_UNRESOLVED",   # stated but not usable (vague, unparseable, deferred)
    "FIELD_NA",           # applicability predicate false
]

GapCode = Literal[
    "GAP_ABSENT",               # field required and missing
    "GAP_VAGUE",                # qualitative where a quantity is needed
    "GAP_UNPARSEABLE",          # present, failed to parse as the declared type
    "GAP_DIMENSION_MISMATCH",   # parsed but wrong physical dimension
    "GAP_OUT_OF_RANGE",         # parsed, right dimension, implausible value
    "GAP_RANGE_NOT_POINT",      # a range where a point value is required
    "GAP_DEFERRED_TO_REF",      # "as previously described (ref N)"
    "GAP_DEFERRED_TO_DISPLAY",  # "the indicated times", "see Fig 3"
]

# GAP_RANGE_NOT_POINT was previously only expressible as a SlotVerdict, so a
# range gap could be detected but not emitted.
#
# GAP_DEFERRED_TO_DISPLAY is separated from GAP_DEFERRED_TO_REF because the two
# behave differently under triage. A deferral to a figure is often recoverable
# (the axis carries the value); a deferral to another paper usually is not, and
# frequently chains into a further deferral. Collapsing them hides that split.

# Which gap codes are legal for which verdict. Enforced on Finding.
_VERDICT_CODES: dict[str, set[str]] = {
    "FIELD_ABSENT": {"GAP_ABSENT"},
    "FIELD_UNRESOLVED": {
        "GAP_VAGUE",
        "GAP_UNPARSEABLE",
        "GAP_DIMENSION_MISMATCH",
        "GAP_OUT_OF_RANGE",
        "GAP_RANGE_NOT_POINT",
        "GAP_DEFERRED_TO_REF",
        "GAP_DEFERRED_TO_DISPLAY",
    },
    "FIELD_OK": set(),   # no gap; a Finding should not exist
    "FIELD_NA": set(),   # predicate false; a Finding should not exist
}

FieldType = Literal["quantity", "enum", "identifier", "sequence", "boolean", "text"]


class FieldSpec(BaseModel):
    field_id: str
    type: FieldType
    dimension: Optional[str] = None          # for quantity fields
    canonical_unit: Optional[str] = None
    plausible_range: Optional[tuple[Decimal, Decimal]] = None
    enum_values: Optional[list[str]] = None
    applies_when: list[StudyFeature] = []      # ALL must hold; empty = always
    applies_when_any: list[StudyFeature] = []  # at least ONE must hold; empty = ignored
    # Both are ANDed together. antibody.identifier needs
    #   applies_when=[has_wet_lab], applies_when_any=[has_western_blot, has_ihc,
    #   has_flow_cytometry]
    # which AND-only semantics could not express.
    provenance: list[dict[str, str]] = []    # guideline + item number
    sensitivity: Literal["HIGH", "MED", "LOW"] = "HIGH"
    sensitivity_source: Literal["expert", "default"] = "default"
    description: str = ""


class FieldPack(BaseModel):
    version: str
    fields: list[FieldSpec]

    def by_id(self, field_id: str) -> Optional[FieldSpec]:
        return next((f for f in self.fields if f.field_id == field_id), None)

    def applicable(self, profile: StudyProfile) -> list[FieldSpec]:
        def applies(f: FieldSpec) -> bool:
            if not all(profile.has(x) for x in f.applies_when):
                return False
            if f.applies_when_any and not any(
                profile.has(x) for x in f.applies_when_any
            ):
                return False
            return True

        return [f for f in self.fields if applies(f)]


